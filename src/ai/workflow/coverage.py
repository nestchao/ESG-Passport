"""Evidence readiness checks, not an emissions calculator or compliance certification."""
from datetime import date,timedelta
from decimal import Decimal, InvalidOperation
import re

WATER_SOURCES={'purchased','surface','groundwater','seawater','produced'}
UNIT={'Wh':('energy',Decimal(1)),'kWh':('energy',Decimal(1000)),
      'MWh':('energy',Decimal(1000000)),'MJ':('energy',Decimal(1000000)/Decimal(3600)),
      'GJ':('energy',Decimal(1000000000)/Decimal(3600)),
      'L':('water',Decimal(1)),'m3':('water',Decimal(1000)),
      'kg':('waste',Decimal('.001')),'t':('waste',Decimal(1)),
      'tCO2e':('emissions',Decimal(1)),'kgCO2e':('emissions',Decimal('.001'))}


def assess_coverage(requirement,evidence,declarations=None):
    """Only explicit reviewed metadata can establish readiness; no inferred zeros.

    Declarations are separate, reviewable owner inputs, not generated by the mapper.
    'direct_evidence' means sufficient for review under this prototype's checks.
    """
    declarations=declarations or {}
    declarations_reviewed=declarations.get('reviewed') is True
    completeness_confirmed=declarations_reviewed and declarations.get('period_completeness_confirmed') is True
    code=requirement['sedg_code']; metric=requirement['metric_id']
    boundary=requirement['boundary']; period=requirement['target_period']
    gaps=[];selected=[];duplicate_count=0
    def response(state,**extra):
        return {'requirement_id':requirement['requirement_id'],'state':state,
            'evidence_ids':[e['evidence_id'] for e in selected],
            'target_period':period,'evidence_periods':[e['period'] for e in selected],
            'issues':list(dict.fromkeys(gaps)),'duplicate_records_removed':duplicate_count,
            'requires_human_review':True,'is_verified_disclosure':False,**extra}
    if not boundary.get('organisation_id'):
        gaps.append('organisation_boundary_required');return response('manual_review')
    if boundary.get('site_required') and not boundary.get('site_id'):
        gaps.append('site_breakdown_required');return response('manual_review')
    try:
        start,end=date.fromisoformat(period['start']),date.fromisoformat(period['end'])
        if start>end:raise ValueError()
    except (ValueError,TypeError,KeyError):
        gaps.append('target_period_required');return response('manual_review')
    matching=[]
    activity_metric={'E1.1':'fuel_consumed','E1.2':'electricity_consumption'}.get(code)
    if code=='E2.1' and metric=='fuel_consumption_energy':activity_metric='fuel_consumed'
    for observation in evidence:
        auxiliary=['waste_transferred'] if code=='E4.1' else []
        if observation.get('metric_id') not in [metric,activity_metric]+auxiliary:continue
        if observation.get('organisation_id')!=boundary['organisation_id']:continue
        if boundary.get('site_id') and observation.get('site_id')!=boundary['site_id']:continue
        matching.append(observation)
    if not matching:
        gaps.append('no_matching_metric_and_boundary_evidence');return response('missing')
    seen={}
    for observation in matching:
        if observation.get('reviewed') is not True or not re.fullmatch(r'[0-9a-f]{64}',observation.get('document_sha256','')):
            gaps.append('evidence_review_or_provenance_required');continue
        if code in ('E1.1','E1.2') and (not boundary.get('consolidation_method') or
                observation.get('consolidation_method')!=boundary.get('consolidation_method')):
            gaps.append('consolidation_boundary_review_required');continue
        try:
            left,right=date.fromisoformat(observation['period']['start']),date.fromisoformat(observation['period']['end'])
            value=Decimal(str(observation['value']))
            if left>right or not value.is_finite() or value<0:raise ValueError()
        except (KeyError,ValueError,TypeError,InvalidOperation):
            gaps.append('invalid_evidence_quantity_or_period');continue
        if right<start or left>end:continue
        if left<start or right>end:
            gaps.append('allocation_required_for_crossing_period');continue
        identity=(observation['document_sha256'],observation['metric_id'],left,right,
                  observation.get('source'),observation.get('site_id'))
        if identity in seen:
            if seen[identity]!=(observation['value'],observation['unit']):
                gaps.append('conflicting_duplicate_records');return response('manual_review')
            duplicate_count+=1;continue
        seen[identity]=(observation['value'],observation['unit'])
        selected.append(observation)
    if not selected:
        return response('partial' if gaps else 'missing')
    if code=='E4.1' and any(e['metric_id']=='waste_transferred' for e in selected):
        gaps.append('waste_transfer_does_not_establish_requested_flow')
        return response('partial')
    if not boundary.get('site_id') and not all(e.get('covers_organisation_boundary') is True for e in selected):
        required_sites=declarations.get('company_site_ids') if declarations_reviewed else None
        if not required_sites or not set(required_sites).issubset({e.get('site_id') for e in selected}):
            gaps.append('company_site_coverage_unconfirmed')
    # Emissions records may be used only with reviewed calculation provenance.
    emission_records=[e for e in selected if e['metric_id']==metric] if code in ('E1.1','E1.2') else []
    if code in ('E1.1','E1.2') and emission_records:
        selected=emission_records
        if any(not e.get('calculation_provenance',{}).get('reviewed') or
               not e['calculation_provenance'].get('method') or
               not e['calculation_provenance'].get('factor_source') or
               not e['calculation_provenance'].get('factor_vintage') for e in selected):
            gaps.append('emissions_calculation_provenance_required');return response('manual_review')
        if code=='E1.2' and any(not e['calculation_provenance'].get('grid_region') or
            not e['calculation_provenance'].get('factor_vintage') or
            not e['calculation_provenance'].get('accounting_method') for e in selected):
            gaps.append('scope2_region_vintage_method_required');return response('manual_review')
    # Coverage is checked within source/site streams. Overlapping bills never sum silently.
    streams={}
    for observation in selected:
        group=(observation['metric_id'],observation.get('source'),observation.get('site_id'))
        streams.setdefault(group,[]).append((date.fromisoformat(observation['period']['start']),date.fromisoformat(observation['period']['end'])))
    for stream,intervals in streams.items():
        cursor=start
        for index,(left,right) in enumerate(sorted(intervals)):
            if index and left<=previous_right:
                gaps.append('overlapping_evidence_requires_review');return response('manual_review')
            previous_right=right
            if left>cursor and not completeness_confirmed:
                gaps.append('partial_period_coverage')
            cursor=max(cursor,right+timedelta(days=1))
        if cursor<=end and not completeness_confirmed:
            gaps.append('partial_period_coverage')
    if code in ('E1.1','E1.2') and not emission_records:
        if code=='E1.2':
            if any(e['unit'] not in ('Wh','kWh','MWh','MJ','GJ') for e in selected):
                gaps.append('scope2_activity_must_be_energy_not_power');return response('manual_review')
            for key in ['grid_region','factor_vintage','factor_source','accounting_method']:
                if not declarations.get(key):gaps.append(key+'_confirmation_required')
            if declarations.get('factor_value') is None:gaps.append('factor_value_required')
            if declarations.get('factor_unit') not in ('kgCO2e/kWh','tCO2e/kWh'):gaps.append('factor_unit_required')
            gaps.append('scope2_factor_application_required')
        else:
            gaps.extend(['fuel_type_and_use_boundary_required','fuel_factor_source_and_vintage_required','scope1_calculation_required'])
        if 'partial_period_coverage' in gaps or 'company_site_coverage_unconfirmed' in gaps:
            return response('partial',calculation_required=True,readiness='partial_activity',calculated_value=None)
        try:
            factor=Decimal(str(declarations.get('factor_value')))
            factor_valid=factor.is_finite() and factor>=0
        except InvalidOperation:factor_valid=False
        ready=(code=='E1.2' and declarations_reviewed and declarations.get('factor_reviewed') is True and factor_valid and
            declarations.get('grid_region') in ('peninsular','sabah','sarawak') and
            declarations.get('accounting_method')=='location_based' and
            declarations.get('factor_unit') in ('kgCO2e/kWh','tCO2e/kWh') and
            all(declarations.get(k) for k in ['factor_vintage','factor_source','factor_selection_justification']))
        return response('calculation_required',readiness='inputs_ready' if ready else 'activity_only',calculated_value=None)
    if code=='E2.1' and any(e['unit']=='L' for e in selected):
        gaps.append('fuel_specific_energy_conversion_required')
        return response('calculation_required',readiness='activity_only',calculated_value=None)
    if code=='E3.1':
        applicability=declarations.get('water_source_applicability',{}) if declarations_reviewed else {}
        if set(applicability)!=WATER_SOURCES or any(type(v) is not bool for v in applicability.values()):
            gaps.append('water_source_applicability_unconfirmed')
        else:
            sources={e.get('source') for e in selected}
            if any(active and source not in sources for source,active in applicability.items()):
                gaps.append('partial_water_source_coverage')
            if any(source not in WATER_SOURCES or not applicability.get(source,False) for source in sources):
                gaps.append('water_source_declaration_conflict')
    if code=='E4.1':
        if metric in ('waste_diverted','waste_disposed') and any(not e.get('treatment_confirmed') for e in selected):
            gaps.append('declared_destination_not_confirmed_treatment')
        if not (declarations_reviewed and declarations.get('waste_flow_completeness_confirmed') is True):
            gaps.append('waste_flow_completeness_unconfirmed')
    expected_dimension={'E1.1':'emissions','E1.2':'emissions','E2.1':'energy','E3.1':'water','E4.1':'waste'}[code]
    total=Decimal(0)
    for observation in selected:
        unit=UNIT.get(observation['unit'])
        if not unit or unit[0]!=expected_dimension:
            gaps.append('unit_dimension_mismatch');return response('manual_review')
        total+=Decimal(str(observation['value']))*unit[1]
    if gaps:return response('partial',normalized_candidate_total=str(total),candidate_unit=requirement['catalogue_units'][0])
    return response('direct_evidence',normalized_candidate_total=str(total),candidate_unit=requirement['catalogue_units'][0])
