"""Boundary and validator regression tests; no live inference or external data."""
import copy
import hashlib
import unittest
from ai.workflow.mapping import map_question,validate_result,validate_fallback


CONTEXT={'boundary':{'organisation_id':'demo-org','site_id':'demo-site','consolidation_method':'operational_control'}}


def req(text,context=None):
    return map_question('q-test',text,CONTEXT if context is None else context)['requirements'][0]


def evidence(metric='electricity_consumption',unit='kWh',value='100',left='2026-01-01',right='2026-12-31',identity='demo-1',**extra):
    return {'evidence_id':identity,'document_sha256':hashlib.sha256(identity.encode()).hexdigest(),
        'organisation_id':'demo-org','site_id':'demo-site','consolidation_method':'operational_control',
        'metric_id':metric,'value':value,'unit':unit,'period':{'start':left,'end':right},'reviewed':True,**extra}


class MappingTests(unittest.TestCase):
    def test_bilingual_codes_agree_without_translation_model(self):
        pairs=[('Report Scope 1 emissions.','Laporkan emisi GHG Skop 1.','E1.1'),
            ('Report Scope 2 emissions.','Laporkan emisi Skop 2.','E1.2'),
            ('Energy consumption in kWh.','Penggunaan tenaga dalam kWh.','E2.1'),
            ('Water withdrawn in litres.','Pengambilan air dalam liter.','E3.1'),
            ('Waste generated in tonnes.','Sisa dijana dalam tan metrik.','E4.1')]
        for en,ms,code in pairs:
            self.assertEqual(map_question('en',en)['codes'],[code])
            self.assertEqual(map_question('ms',ms)['codes'],[code])

    def test_compound_creates_two_requirements_without_answers(self):
        result=map_question('q','Report electricity consumption in kWh and Scope 2 emissions in tCO2e for 2026.')
        self.assertEqual(result['codes'],['E1.2','E2.1'])
        self.assertEqual(len(result['requirements']),2)
        self.assertTrue(all('value' not in r for r in result['requirements']))

    def test_diversion_does_not_create_disposed_flow(self):
        result=map_question('q','Report waste diverted from disposal in 2026 in tonnes.')
        self.assertEqual([r['metric_id'] for r in result['requirements']],['waste_diverted'])

    def test_three_waste_flows_decompose_under_one_code(self):
        result=map_question('q','Report waste generated, diverted from disposal and directed to disposal.')
        self.assertEqual(result['codes'],['E4.1'])
        self.assertEqual({r['metric_id'] for r in result['requirements']},{'waste_generated','waste_diverted','waste_disposed'})

    def test_water_consumption_and_unknown_scope_abstain(self):
        for text in ['Report water consumption.','Report total GHG emissions.']:
            result=map_question('q',text)
            self.assertEqual(result['codes'],[])
            self.assertEqual(result['mapping_status'],'ambiguous')

    def test_intermediate_waste_is_outside_basic_scope(self):
        result=map_question('q','Report waste generated by hazardous and non-hazardous type.')
        self.assertEqual(result['codes'],['E4.2'])
        self.assertEqual(result['mapping_status'],'outside_scope')
        self.assertEqual(result['requirements'],[])

    def test_negated_codes_are_not_positive_labels(self):
        result=map_question('q','Exclude Scope 1 and report Scope 2.')
        self.assertEqual(result['codes'],[])
        self.assertEqual(result['mapping_status'],'needs_review')

    def test_fiscal_dates_are_not_guessed(self):
        result=req('Report water withdrawn for FY2026 in litres.')
        self.assertEqual(result['target_period'],{'start':None,'end':None})
        self.assertIn('fiscal_dates_required',result['missing_inputs'])

    def test_site_requirement_does_not_default_to_company_total(self):
        result=req('Report Scope 2 emissions for each site in 2026.',{'boundary':{
            'organisation_id':'demo-org','site_id':None,'consolidation_method':'operational_control'}})
        self.assertTrue(result['boundary']['site_required'])
        self.assertIn('site_breakdown_required',result['missing_inputs'])

    def test_validator_rejects_unknown_code_tier_units_and_invented_provenance(self):
        original=map_question('q','Report water withdrawn in 2026 in litres.')
        cases=[]
        a=copy.deepcopy(original);a['codes']=['E99.1'];cases.append(a)
        a=copy.deepcopy(original);a['requirements'][0]['level']='advanced';cases.append(a)
        a=copy.deepcopy(original);a['requirements'][0]['requested_unit']='tCO2e';cases.append(a)
        a=copy.deepcopy(original);a['requirements'][0]['question_span']['text']='made up';cases.append(a)
        for value in cases:
            self.assertEqual(validate_fallback(value,'q',original['original_text'])['status'],'manual_review')
